#!/usr/bin/env python3
"""Generate cfn/update_types.go from AWS's CloudFormation resource specification.

Each property of a resource type has an UpdateType in AWS's resource specification: Mutable (an update changes
the resource in place), Immutable (an update replaces it) or Conditional (it may). A change set reports a
modified resource's Replacement from the properties that change. This writes the non-Mutable properties of the
types the engine knows (every AWS::<Service>::<Type> its source names) into update_types.go.

    curl -sSfL https://d1uauaxba7bl26.cloudfront.net/latest/gzip/CloudFormationResourceSpecification.json \\
      | gunzip > /tmp/spec.json
    python3 cfn/gen_update_types.py /tmp/spec.json
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "update_types.go"
TYPE_RE = re.compile(r'"(AWS::[A-Za-z0-9]+::[A-Za-z0-9]+)"')


def known_types():
    types = set()
    for p in HERE.glob("*.go"):
        if p.name.endswith("_test.go") or p.name == OUT.name:
            continue
        types.update(TYPE_RE.findall(p.read_text()))
    return types


def main(spec_path):
    spec = json.loads(pathlib.Path(spec_path).read_text())
    version = spec.get("ResourceSpecificationVersion", "unknown")
    rows = []
    for typ in sorted(known_types()):
        rt = spec["ResourceTypes"].get(typ)
        if rt is None:
            continue
        props = {k: v.get("UpdateType") for k, v in rt.get("Properties", {}).items()
                 if v.get("UpdateType") in ("Immutable", "Conditional")}
        if props:
            rows.append((typ, props))
    lines = [
        "// Code generated by cfn/gen_update_types.py from the AWS CloudFormation resource specification",
        f"// (version {version}); DO NOT EDIT.",
        "",
        "package cfn",
        "",
        "// updateTypes are each resource type's properties whose update is not Mutable, as AWS's resource",
        "// specification gives them: Immutable (an update replaces the resource) or Conditional (it may). A",
        "// property not listed is Mutable.",
        "var updateTypes = map[string]map[string]string{",
    ]
    for typ, props in rows:
        items = ", ".join(f'"{k}": "{v}"' for k, v in sorted(props.items()))
        lines.append(f'\t"{typ}": {{{items}}},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    try:  # aligned as gofmt aligns it, so the generated file is gofmt-clean
        import subprocess
        subprocess.run(["gofmt", "-w", str(OUT)], check=True)
    except (OSError, subprocess.CalledProcessError):
        print("note: gofmt not found; run gofmt -w cfn/update_types.go", file=sys.stderr)
    print(f"wrote {OUT.relative_to(HERE.parent)}: {len(rows)} types (spec {version})")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
